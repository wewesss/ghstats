const dictionary: Record<Locale, Record<Key, string>> = { en, fr };

export function locale(): Locale {
  if (typeof document === "undefined") return "en";
  return document.documentElement.lang.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function t(key: Key, values?: Record<string, string | number>): string {
  const text = dictionary[locale()][key];
  if (values === undefined) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (Object.hasOwn(values, name) ? String(values[name]) : match));
}
